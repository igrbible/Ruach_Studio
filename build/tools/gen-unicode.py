#!/usr/bin/env python3
# Generate src/unicode-table.h from the Python unicodedata database.
# Emits what the frozen tokenizer needs: canonical decomposition and
# composition for NFC, canonical combining classes, and the letter and
# number ranges the pre-tokenizer pattern matches.
#
# Usage: ./tools/gen-unicode.py

import os
import sys
import unicodedata

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
OUTPUT = os.path.join(SCRIPT_DIR, "..", "src", "unicode-table.h")

HANGUL_S_BASE = 0xAC00
HANGUL_S_COUNT = 11172

def collect():
    dec = []      # (cp, a, b) with b = 0 for a singleton
    comp = []     # (a, b, cp) for the pairs NFC recomposes
    ccc = []      # (first, last, class)
    letters = []  # (first, last) over category L*
    numbers = []  # (first, last) over category N*

    ccc_runs, letter_runs, number_runs = [], [], []
    for cp in range(0x110000):
        ch = chr(cp)
        d = unicodedata.decomposition(ch)
        if d and not d.startswith("<"):
            parts = [int(x, 16) for x in d.split()]
            a = parts[0]
            b = parts[1] if len(parts) > 1 else 0
            dec.append((cp, a, b))
            # A pair recomposes unless the code point carries the full
            # composition exclusion property, which the normalizer itself
            # answers without a separate exclusion list.
            if b and unicodedata.normalize("NFC", chr(a) + chr(b)) == ch:
                comp.append((a, b, cp))
        c = unicodedata.combining(ch)
        if c:
            ccc_runs.append((cp, c))
        cat = unicodedata.category(ch)[0]
        if cat == "L":
            letter_runs.append(cp)
        elif cat == "N":
            number_runs.append(cp)

    def pack_valued(pairs):
        out = []
        for cp, v in pairs:
            if out and out[-1][1] == cp - 1 and out[-1][2] == v:
                out[-1] = (out[-1][0], cp, v)
            else:
                out.append((cp, cp, v))
        return out

    def pack_plain(points):
        out = []
        for cp in points:
            if out and out[-1][1] == cp - 1:
                out[-1] = (out[-1][0], cp)
            else:
                out.append((cp, cp))
        return out

    ccc = pack_valued(ccc_runs)
    letters = pack_plain(letter_runs)
    numbers = pack_plain(number_runs)
    comp.sort(key=lambda e: (e[0], e[1]))
    return dec, comp, ccc, letters, numbers

def emit_rows(f, rows, per_line, fmt):
    for i in range(0, len(rows), per_line):
        f.write("    " + " ".join(fmt(r) for r in rows[i:i + per_line]) + "\n")

def main():
    dec, comp, ccc, letters, numbers = collect()
    with open(OUTPUT, "w") as f:
        f.write("#pragma once\n")
        f.write("// unicode-table.h: Unicode %s data for the frozen tokenizer.\n" % unicodedata.unidata_version)
        f.write("// Generated by tools/gen-unicode.py, sorted for binary search.\n")
        f.write("//\n")
        f.write("// DEC:  code point, first part, second part (0 for a singleton)\n")
        f.write("// COMP: first part, second part, composed code point\n")
        f.write("// CCC:  range first, range last, canonical combining class\n")
        f.write("// L, N: ranges of the letter and number categories\n")
        f.write("//\n")
        f.write("// Hangul syllables are algorithmic and carry no table entry.\n")
        f.write("\n#include <cstdint>\n\n")

        f.write("static const uint32_t UNI_DEC[][3] = {\n")
        emit_rows(f, dec, 3, lambda r: "{ 0x%04X, 0x%04X, 0x%04X }," % r)
        f.write("};\n\n")

        f.write("static const uint32_t UNI_COMP[][3] = {\n")
        emit_rows(f, comp, 3, lambda r: "{ 0x%04X, 0x%04X, 0x%04X }," % r)
        f.write("};\n\n")

        f.write("static const uint32_t UNI_CCC[][3] = {\n")
        emit_rows(f, ccc, 4, lambda r: "{ 0x%04X, 0x%04X, %3d }," % r)
        f.write("};\n\n")

        f.write("static const uint32_t UNI_LETTER[][2] = {\n")
        emit_rows(f, letters, 5, lambda r: "{ 0x%04X, 0x%04X }," % r)
        f.write("};\n\n")

        f.write("static const uint32_t UNI_NUMBER[][2] = {\n")
        emit_rows(f, numbers, 5, lambda r: "{ 0x%04X, 0x%04X }," % r)
        f.write("};\n")

    sys.stderr.write("[Unicode] %d decompositions, %d compositions, %d ccc runs, %d letter ranges, %d number ranges\n"
                     % (len(dec), len(comp), len(ccc), len(letters), len(numbers)))
    sys.stderr.write("[Unicode] Hangul: %d algorithmic syllables from U+%04X\n" % (HANGUL_S_COUNT, HANGUL_S_BASE))
    sys.stderr.write("[Unicode] Wrote %s\n" % os.path.normpath(OUTPUT))

main()
