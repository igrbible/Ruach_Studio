  function tpPitch(p, t) {
    var T = R.tp, K = keyInfo(t), deg = ((p - K.tonic) % 12 + 12) % 12, minor = K.minor;
    if (T.mode === "minor" && !K.minor) { if (deg === 4 || deg === 9 || deg === 11) p -= 1; minor = true; }
    else if (T.mode === "major" && K.minor) { if (deg === 3 || deg === 8 || deg === 10) p += 1; minor = false; }
    var sh = Math.round(tpAt(t)), q = p + sh;
    if (T.key) {                                       // out of the key: to the nearest note in it, the way the shift went
      var scale = minor ? [0, 2, 3, 5, 7, 8, 10] : [0, 2, 4, 5, 7, 9, 11], dir = sh < 0 ? -1 : 1;
      for (var g = 0; g < 2 && scale.indexOf(((q - K.tonic) % 12 + 12) % 12) < 0; g++) q += dir;
    }
    return Math.max(0, Math.min(127, q));
  }
